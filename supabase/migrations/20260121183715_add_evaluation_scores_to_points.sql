/*
  # Add Evaluation Scores to Prompt Points

  1. Changes
    - Add `evaluation_score` column to `prompt_points` table
      - Stores a score from 0 to 100 evaluating the quality of responses
      - Generated by a separate evaluator LLM
    - Add `evaluation_feedback` column to store qualitative feedback
    - Add `evaluated_by_model` column to track which LLM did the evaluation
    - Add `evaluated_at` timestamp

  2. Notes
    - Evaluation scores help assess the quality and completeness of point responses
    - Separate from confidence scores - evaluation is a meta-analysis of answer quality
*/

-- Add evaluation columns to prompt_points
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'prompt_points' AND column_name = 'evaluation_score'
  ) THEN
    ALTER TABLE prompt_points ADD COLUMN evaluation_score decimal(5,2) CHECK (evaluation_score >= 0 AND evaluation_score <= 100);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'prompt_points' AND column_name = 'evaluation_feedback'
  ) THEN
    ALTER TABLE prompt_points ADD COLUMN evaluation_feedback text;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'prompt_points' AND column_name = 'evaluated_by_model'
  ) THEN
    ALTER TABLE prompt_points ADD COLUMN evaluated_by_model text;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'prompt_points' AND column_name = 'evaluated_at'
  ) THEN
    ALTER TABLE prompt_points ADD COLUMN evaluated_at timestamptz;
  END IF;
END $$;

-- Add index for evaluation scores
CREATE INDEX IF NOT EXISTS idx_prompt_points_evaluation_score ON prompt_points(evaluation_score);
